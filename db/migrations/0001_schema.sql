-- Esquema do Cotador. Idempotente: pode rodar de novo sem efeito.

create extension if not exists pg_trgm;

create table if not exists produtos (
    id                   integer primary key generated by default as identity,
    codigo               text    not null unique,
    descricao            text    not null,
    atributos            jsonb   not null default '{}',
    preco_custo_centavos integer not null default 0 check (preco_custo_centavos >= 0),
    ncm                  text    not null default ''
);

-- KNN por trigrama: `order by descricao <-> texto` usa este índice.
create index if not exists produtos_descricao_trgm on produtos using gist (descricao gist_trgm_ops);

-- Memória de pares (texto do cliente -> produto) confirmados pelo operador.
-- `escopo` é 'cnpj:<8 dígitos>', 'nome:<nome normalizado>' ou '' (sem identificação).
create table if not exists match_memoria (
    entrada_norm text    not null,
    escopo       text    not null,
    produto_id   integer not null references produtos (id) on delete cascade,
    acertos      integer not null default 0,
    erros        integer not null default 0,
    ultima_vez   timestamptz not null default now(),
    primary key (entrada_norm, escopo, produto_id)
);
create index if not exists match_memoria_entrada on match_memoria (entrada_norm);

create table if not exists propostas (
    id              integer primary key generated by default as identity,
    numero          text    not null unique,
    referencia      text    not null default '',
    cliente         text    not null default '',
    cnpj            text    not null default '',
    destino         text    not null default '',
    frete_centavos  integer not null default 0 check (frete_centavos >= 0),
    prazo_entrega   text    not null default '',
    observacoes     text    not null default '',
    avisos          jsonb   not null default '[]',
    criada_em       timestamptz not null default now()
);

create table if not exists itens_proposta (
    proposta_id         integer not null references propostas (id) on delete cascade,
    n                   integer not null,
    descricao_original  text    not null,
    quantidade          numeric(12, 2) not null default 1,
    unidade             text    not null default 'UN',
    atributos           jsonb   not null default '{}',
    produto_id          integer references produtos (id),
    confianca           text    not null default 'nenhuma',
    origem              text    not null default 'nenhuma',
    motivo              text    not null default '',
    preco_un_centavos   integer not null default 0 check (preco_un_centavos >= 0),
    candidatos          jsonb   not null default '[]',
    primary key (proposta_id, n)
);

create table if not exists extracao_cache (
    chave      text primary key,
    valor      jsonb not null,
    criada_em  timestamptz not null default now()
);

-- Camada 2: top-N candidatos por descrição, todas numa ida ao banco.
create or replace function candidatos_trgm_lote(descs text[], n integer)
returns table (
    idx integer, id integer, codigo text, descricao text, atributos jsonb,
    preco_custo_centavos integer, ncm text, sim real
)
language sql stable as $$
    select d.i::integer, p.id, p.codigo, p.descricao, p.atributos, p.preco_custo_centavos, p.ncm, p.sim
    from unnest(descs) with ordinality as d(txt, i)
    cross join lateral (
        select pr.*, similarity(pr.descricao, d.txt) as sim
        from produtos pr
        order by pr.descricao <-> d.txt
        limit n
    ) p
    order by d.i, p.sim desc, p.id
$$;

-- Camada 1: o cliente vence o global; dentro do escopo vale o maior saldo
-- (acertos - erros) e empate no topo é ambiguidade, então não responde.
create or replace function memoria_match(entradas text[], escopo_cliente text)
returns table (entrada_norm text, produto_id integer, origem text)
language sql stable as $$
    with pedidas as (select distinct e as entrada_norm from unnest(entradas) e where e <> ''),
    cliente as (
        select m.entrada_norm, m.produto_id, m.acertos - m.erros as saldo
        from match_memoria m join pedidas p using (entrada_norm)
        where m.escopo = escopo_cliente and escopo_cliente <> '' and m.acertos - m.erros > 0
    ),
    cliente_topo as (
        select entrada_norm, (array_agg(produto_id))[1] as produto_id
        from cliente c
        where saldo = (select max(saldo) from cliente x where x.entrada_norm = c.entrada_norm)
        group by entrada_norm
        having count(*) = 1
    ),
    global as (
        select m.entrada_norm, m.produto_id, sum(m.acertos - m.erros) as saldo
        from match_memoria m join pedidas p using (entrada_norm)
        group by m.entrada_norm, m.produto_id
        having sum(m.acertos - m.erros) > 0
    ),
    global_topo as (
        select entrada_norm, (array_agg(produto_id))[1] as produto_id
        from global g
        where saldo = (select max(saldo) from global x where x.entrada_norm = g.entrada_norm)
        group by entrada_norm
        having count(*) = 1
    )
    select entrada_norm, produto_id, 'memoria_cliente' from cliente_topo
    union all
    select g.entrada_norm, g.produto_id, 'memoria_global'
    from global_topo g
    where g.entrada_norm not in (select entrada_norm from cliente_topo)
$$;
